import { describe, expect, it } from 'vitest'
import migrationSql from '../../supabase/migrations/20261105010000_work_orders.sql?raw'

const sql = migrationSql.toLowerCase().replace(/--.*$/gm, '').replace(/\s+/g, ' ')

function functionBody(name: string) {
  const start = sql.indexOf(`function public.${name}(`)
  expect(start).toBeGreaterThan(-1)
  const open = sql.indexOf('$$', start)
  return sql.slice(open, sql.indexOf('$$', open + 2))
}

describe('work orders migration', () => {
  it('is additive: only new tables, no changes to existing tables or rows', () => {
    expect(sql).not.toMatch(/drop table|drop column|truncate|alter column|add column/)
    expect(sql).not.toMatch(/alter table public\.(projects|profiles|project_assignments|documents|notifications)/)
    expect(sql).not.toMatch(/(update|delete from) public\.(projects|profiles|project_assignments|documents)/)
    const droppedPolicies = [...sql.matchAll(/drop policy if exists "([^"]+)"/g)].map((m) => m[1])
    const createdPolicies = [...sql.matchAll(/create policy "([^"]+)"/g)].map((m) => m[1])
    expect(droppedPolicies.every((name) => createdPolicies.includes(name))).toBe(true)
    expect(createdPolicies.every((name) => name.toLowerCase().includes('work order'))).toBe(true)
  })

  it('has every Work Order field and the five statuses', () => {
    for (const column of [
      'work_order_number bigint generated by default as identity (start with 1001) unique',
      'project_id uuid not null references public.projects',
      'subcontractor_id uuid not null references public.profiles',
      'trade text',
      'title text not null',
      'scope_of_work text',
      'measurements_and_specs text',
      'important_requirements text',
      'agreed_price numeric(12, 2)',
      'start_date date',
      'target_completion_date date',
      'payment_notes text',
      'warranty_applies boolean not null default false',
      'warranty_notes text',
      "status text not null default 'assigned'",
    ]) {
      expect(sql).toContain(column)
    }
    expect(sql).toContain("check (status in ('assigned', 'accepted', 'in_progress', 'work_completed', 'closed'))")
  })

  it('subcontractors only see their own work orders; only management writes them', () => {
    expect(sql).toMatch(/view work orders" on public\.work_orders for select .*or subcontractor_id = auth\.uid\(\)/)
    expect(sql).toMatch(
      /"management manage work orders" on public\.work_orders for all to authenticated using \(public\.has_management_role\(\) and public\.same_organization\(organization_id\)\)/,
    )
    expect(sql).toContain("p.role = 'subcontractor' and p.organization_id = v_project.organization_id")
  })

  it('updates are added only through the function (no direct insert policy)', () => {
    expect(sql).toContain('revoke all on public.work_orders, public.work_order_updates, public.work_order_files from anon, authenticated')
    expect(sql).toContain('grant select on public.work_order_updates to authenticated')
    expect(sql).not.toMatch(/on public\.work_order_updates for (insert|update|all)/)
    expect(sql).not.toMatch(/on public\.work_order_files for update/)
  })

  it('stores files in a private work-order-files bucket scoped by work order', () => {
    expect(sql).toContain("values ('work-order-files', 'work-order-files', false)")
    expect(sql).toContain("bucket_id = 'work-order-files' and public.can_access_work_order(public.work_order_folder_id(name))")
    expect(sql).toContain("(storage.foldername(name))[2] = 'reference' and public.can_manage_work_order")
    expect(sql).toContain("storage_path like work_order_id::text || '/reference/%'")
    expect(sql).not.toMatch(/bucket_id = '(documents|project-files|restricted-documents)'/)
  })

  it('subcontractors get the project name and job address only — no financials or client contact', () => {
    const body = functionBody('work_order_project_summaries')
    expect(body).toContain('p.name')
    expect(body).toContain('job_site_address')
    expect(body).toContain('public.can_access_work_order(w.id)')
    expect(body).not.toMatch(/budget|contract|payment|client|phone|email|price/)
  })

  it('status flow: accept, start (Ready to Work only), complete; only management closes', () => {
    const body = functionBody('update_work_order_status')
    expect(body).toContain("p_action = 'accept' and v_row.status = 'assigned'")
    expect(body).toContain("p_action = 'start' and v_row.status = 'accepted'")
    expect(body).toContain("v_ready is distinct from 'ready'")
    expect(body).toContain("p_action = 'complete' and v_row.status = 'in_progress'")
    expect(body).toContain("v_next := 'work_completed'")
    expect(body).toContain('only management can close a work order')
    expect(body).toContain('only the assigned subcontractor can update this work order')
    expect(body).toMatch(/'work order completed'.*p\.role in \('admin', 'project_manager'\)/)
  })

  it('updates need an In Progress work order and photos already uploaded under updates/', () => {
    const body = functionBody('add_work_order_update')
    expect(body).toContain("v_row.subcontractor_id = auth.uid() and v_row.status <> 'in_progress'")
    expect(body).toContain("v_row.status = 'closed'")
    expect(body).toContain('jsonb_array_length(v_photos) > 20')
    expect(body).toContain("v_path not like v_row.id::text || '/updates/%'")
    expect(body).toContain("o.bucket_id = 'work-order-files' and o.name = v_path")
    expect(body).toContain("'work order question'")
  })

  it('every security definer function pins search_path and is not callable by anon', () => {
    const definers = sql.split('create or replace function').slice(1).filter((part) => part.includes('security definer'))
    expect(definers.length).toBeGreaterThanOrEqual(6)
    for (const part of definers) expect(part).toContain('set search_path = public')
    for (const name of ['update_work_order_status', 'add_work_order_update', 'work_order_project_summaries', 'can_access_work_order']) {
      expect(sql).toMatch(new RegExp(`revoke all on function public\\.${name}\\([^)]*\\) from public, anon`))
    }
  })
})
