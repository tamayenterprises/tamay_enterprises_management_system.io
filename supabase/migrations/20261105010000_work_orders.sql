  on public.work_orders for select
  to authenticated
  using (
    public.is_approved_user()
    and (
      (public.has_management_role() and public.same_organization(organization_id))
      or subcontractor_id = auth.uid()
    )
  );

drop policy if exists "Management manage work orders" on public.work_orders;
create policy "Management manage work orders"
  on public.work_orders for all
  to authenticated
  using (public.has_management_role() and public.same_organization(organization_id))
  with check (public.has_management_role() and public.same_organization(organization_id));

drop policy if exists "Management or assigned subcontractor view work order updates" on public.work_order_updates;
create policy "Management or assigned subcontractor view work order updates"
  on public.work_order_updates for select
  to authenticated
  using (public.can_access_work_order(work_order_id));

drop policy if exists "Management or assigned subcontractor view work order files" on public.work_order_files;
create policy "Management or assigned subcontractor view work order files"
  on public.work_order_files for select
  to authenticated
  using (public.can_access_work_order(work_order_id));

drop policy if exists "Management add work order reference files" on public.work_order_files;
create policy "Management add work order reference files"
  on public.work_order_files for insert
  to authenticated
  with check (
    kind = 'reference'
    and uploaded_by = auth.uid()
    and public.can_manage_work_order(work_order_id)
    and storage_path like work_order_id::text || '/reference/%'
  );

drop policy if exists "Management remove work order files" on public.work_order_files;
create policy "Management remove work order files"
  on public.work_order_files for delete
  to authenticated
  using (public.can_manage_work_order(work_order_id));

