create policy "Work order files removed by management"
  on storage.objects for delete
  to authenticated
  using (bucket_id = 'work-order-files' and public.can_manage_work_order(public.work_order_folder_id(name)));

-- ---------------------------------------------------------------------------
-- 4. Project name + job address for work orders (subcontractors cannot read projects)
-- ---------------------------------------------------------------------------
create or replace function public.work_order_project_summaries(p_work_order_ids uuid[])
returns table (work_order_id uuid, project_id uuid, project_name text, job_address text)
language sql
stable
security definer
set search_path = public
as $$
  select w.id, p.id, p.name, coalesce(nullif(btrim(p.job_site_address), ''), nullif(btrim(p.location), ''))
  from public.work_orders w
  join public.projects p on p.id = w.project_id
  where w.id = any (coalesce(p_work_order_ids, '{}'::uuid[]))
    and public.can_access_work_order(w.id);
$$;

revoke all on function public.work_order_project_summaries(uuid[]) from public, anon;
grant execute on function public.work_order_project_summaries(uuid[]) to authenticated;

-- ---------------------------------------------------------------------------
-- 5. Status changes
--    Subcontractor: accept (assigned -> accepted), start (accepted -> in_progress, Ready to Work only),
--    complete (in_progress -> work_completed). Management: close (any open status -> closed).
-- ---------------------------------------------------------------------------
create or replace function public.update_work_order_status(p_work_order_id uuid, p_action text)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_row public.work_orders%rowtype;
  v_me public.profiles%rowtype;
  v_next text;
  v_ready text;
  v_name text;
begin
  select * into v_row from public.work_orders where id = p_work_order_id for update;
  if not found or not public.can_access_work_order(p_work_order_id) then
    raise exception 'Work order not found' using errcode = '42501';
  end if;
  select * into v_me from public.profiles where id = auth.uid();

  if p_action = 'close' then
    if not public.can_manage_work_order(p_work_order_id) then
      raise exception 'Only management can close a work order' using errcode = '42501';
    end if;
    if v_row.status = 'closed' then
      raise exception 'This work order is already closed' using errcode = '22023';
    end if;
    update public.work_orders set status = 'closed', closed_at = now() where id = v_row.id;
    insert into public.notifications (organization_id, recipient_id, title, message, link, entity_type, entity_id)
    values (v_row.organization_id, v_row.subcontractor_id, 'Work Order closed',
      'WO-' || v_row.work_order_number || ' · ' || v_row.title || ' was closed by Tamay.',
      '/work-orders/' || v_row.id, 'work_order', v_row.id);
    return 'closed';
  end if;

  if v_row.subcontractor_id is distinct from auth.uid() then
    raise exception 'Only the assigned subcontractor can update this work order' using errcode = '42501';
  end if;

  if p_action = 'accept' and v_row.status = 'assigned' then
    v_next := 'accepted';
    update public.work_orders set status = v_next, accepted_at = now() where id = v_row.id;
  elsif p_action = 'start' and v_row.status = 'accepted' then
    if to_regprocedure('public.subcontractor_readiness(uuid[])') is not null then
      select r.status into v_ready from public.subcontractor_readiness(array[auth.uid()]) r;
      if v_ready is distinct from 'ready' then
        raise exception 'Complete your setup before starting work' using errcode = '42501';
      end if;
    end if;
    v_next := 'in_progress';
    update public.work_orders set status = v_next, started_at = now() where id = v_row.id;
  elsif p_action = 'complete' and v_row.status = 'in_progress' then
    v_next := 'work_completed';
    update public.work_orders set status = v_next, completed_at = now() where id = v_row.id;
    v_name := coalesce(nullif(btrim(v_me.company_name), ''), btrim(v_me.first_name || ' ' || v_me.last_name));
    insert into public.notifications (organization_id, recipient_id, title, message, link, entity_type, entity_id)
    select v_row.organization_id, p.id, 'Work order completed',
      v_name || ' marked WO-' || v_row.work_order_number || ' · ' || v_row.title || ' completed.',
      '/work-orders/' || v_row.id, 'work_order', v_row.id
    from public.profiles p
    where p.organization_id = v_row.organization_id and p.role in ('admin', 'project_manager')
      and p.approval_status = 'approved' and p.is_active and p.archived_at is null;
  else
    raise exception 'This action is not available for a % work order', replace(v_row.status, '_', ' ') using errcode = '22023';
  end if;
  return v_next;
end;
$$;

revoke all on function public.update_work_order_status(uuid, text) from public, anon;
grant execute on function public.update_work_order_status(uuid, text) to authenticated;

-- ---------------------------------------------------------------------------
-- 6. Work updates (Tamay internal only)
--    p_photos: [{"path": "...", "name": "...", "mime_type": "...", "file_size": 123}, ...]
--    Photos must already be uploaded to work-order-files under {work_order_id}/updates/.
-- ---------------------------------------------------------------------------
create or replace function public.add_work_order_update(
  p_work_order_id uuid,
  p_completed_today text default null,
  p_next_steps text default null,
  p_issue_question text default null,
  p_photos jsonb default '[]'::jsonb
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_row public.work_orders%rowtype;
  v_me public.profiles%rowtype;
  v_id uuid;
  v_photo jsonb;
  v_path text;
  v_done text := nullif(left(btrim(coalesce(p_completed_today, '')), 2000), '');
  v_next text := nullif(left(btrim(coalesce(p_next_steps, '')), 2000), '');
  v_issue text := nullif(left(btrim(coalesce(p_issue_question, '')), 2000), '');
  v_photos jsonb := coalesce(p_photos, '[]'::jsonb);
begin
  select * into v_row from public.work_orders where id = p_work_order_id;
  if not found or not public.can_access_work_order(p_work_order_id) then
    raise exception 'Work order not found' using errcode = '42501';
  end if;
  select * into v_me from public.profiles where id = auth.uid();
  if v_row.subcontractor_id = auth.uid() and v_row.status <> 'in_progress' then
    raise exception 'Start the work order before adding updates' using errcode = '22023';
  end if;
  if v_row.status = 'closed' then
    raise exception 'This work order is closed' using errcode = '22023';
  end if;
  if jsonb_typeof(v_photos) <> 'array' or jsonb_array_length(v_photos) > 20 then
    raise exception 'Up to 20 photos per update' using errcode = '22023';
  end if;
  if v_done is null and v_next is null and v_issue is null and jsonb_array_length(v_photos) = 0 then
    raise exception 'Write an update or add a photo' using errcode = '22023';
  end if;

  insert into public.work_order_updates (work_order_id, organization_id, author_id, completed_today, next_steps, issue_question)
  values (v_row.id, v_row.organization_id, auth.uid(), v_done, v_next, v_issue)
  returning id into v_id;

  for v_photo in select * from jsonb_array_elements(v_photos) loop
    v_path := v_photo ->> 'path';
    if v_path is null or v_path not like v_row.id::text || '/updates/%' or position('..' in v_path) > 0
      or not exists (select 1 from storage.objects o where o.bucket_id = 'work-order-files' and o.name = v_path) then
      raise exception 'Upload each photo before saving the update' using errcode = '22023';
    end if;
    insert into public.work_order_files (work_order_id, update_id, organization_id, uploaded_by, kind, name, storage_path, mime_type, file_size)
    values (
      v_row.id, v_id, v_row.organization_id, auth.uid(), 'update_photo',
      left(coalesce(nullif(btrim(v_photo ->> 'name'), ''), 'photo'), 200), v_path,
      v_photo ->> 'mime_type', nullif(v_photo ->> 'file_size', '')::bigint
    );
  end loop;

  if v_row.subcontractor_id = auth.uid() then
    insert into public.notifications (organization_id, recipient_id, title, message, link, entity_type, entity_id)
    select v_row.organization_id, p.id,
      case when v_issue is not null then 'Work order question' else 'Work order update' end,
      coalesce(nullif(btrim(v_me.company_name), ''), btrim(v_me.first_name || ' ' || v_me.last_name))
        || ' · WO-' || v_row.work_order_number || ': ' || left(coalesce(v_issue, v_done, v_next, 'Added photos'), 140),
      '/work-orders/' || v_row.id, 'work_order_update', v_id
    from public.profiles p
    where p.organization_id = v_row.organization_id and p.role in ('admin', 'project_manager')
      and p.approval_status = 'approved' and p.is_active and p.archived_at is null;
  end if;

  return v_id;
end;
$$;

revoke all on function public.add_work_order_update(uuid, text, text, text, jsonb) from public, anon;
grant execute on function public.add_work_order_update(uuid, text, text, text, jsonb) to authenticated;

