-- Work Orders MVP: the specific work Tamay assigns to a subcontractor on an existing project.
--
-- PROJECT = the full Tamay / client project. WORK ORDER = one subcontractor's assignment on it.
-- Subcontractors see their own work orders (incl. the agreed price), the project name and job address
-- only — never project financials or client contact details.
--
-- ADDITIVE ONLY: three new tables, one new private bucket, new functions and policies. No existing
-- table, policy or row is changed. Work Hub can later create work orders through the same table.
-- Safe to re-run. Rollback steps at the end.

-- ---------------------------------------------------------------------------
-- 1. Tables
-- ---------------------------------------------------------------------------
create table if not exists public.work_orders (
  id uuid primary key default gen_random_uuid(),
  work_order_number bigint generated by default as identity (start with 1001) unique,
  organization_id uuid not null references public.organizations (id) on delete cascade,
  project_id uuid not null references public.projects (id) on delete cascade,
  subcontractor_id uuid not null references public.profiles (id) on delete restrict,
  trade text,
  title text not null,
  scope_of_work text,
  measurements_and_specs text,
  important_requirements text,
  agreed_price numeric(12, 2),
  start_date date,
  target_completion_date date,
  payment_notes text,
  warranty_applies boolean not null default false,
  warranty_notes text,
  status text not null default 'assigned',
  accepted_at timestamptz,
  started_at timestamptz,
  completed_at timestamptz,
  closed_at timestamptz,
  created_by uuid references public.profiles (id) on delete set null,
  updated_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint work_orders_status_check check (status in ('assigned', 'accepted', 'in_progress', 'work_completed', 'closed')),
  constraint work_orders_title_check check (char_length(btrim(title)) between 1 and 160),
  constraint work_orders_price_check check (agreed_price is null or agreed_price >= 0),
  constraint work_orders_dates_check check (
    start_date is null or target_completion_date is null or target_completion_date >= start_date
  ),
  constraint work_orders_text_length check (
    char_length(coalesce(trade, '')) <= 120
    and char_length(coalesce(scope_of_work, '')) <= 5000
    and char_length(coalesce(measurements_and_specs, '')) <= 5000
    and char_length(coalesce(important_requirements, '')) <= 3000
    and char_length(coalesce(payment_notes, '')) <= 1000
    and char_length(coalesce(warranty_notes, '')) <= 2000
  )
);

create index if not exists work_orders_project_idx on public.work_orders (project_id, created_at desc);
create index if not exists work_orders_subcontractor_idx on public.work_orders (subcontractor_id, status);

create table if not exists public.work_order_updates (
  id uuid primary key default gen_random_uuid(),
  work_order_id uuid not null references public.work_orders (id) on delete cascade,
  organization_id uuid not null references public.organizations (id) on delete cascade,
  author_id uuid references public.profiles (id) on delete set null,
  completed_today text,
  next_steps text,
  issue_question text,
  created_at timestamptz not null default now(),
  constraint work_order_updates_text_length check (
    char_length(coalesce(completed_today, '')) <= 2000
    and char_length(coalesce(next_steps, '')) <= 2000
    and char_length(coalesce(issue_question, '')) <= 2000
  )
);

create index if not exists work_order_updates_work_order_idx on public.work_order_updates (work_order_id, created_at desc);

-- Reference files (management) and update photos (subcontractor). Files live in the private
-- work-order-files bucket under {work_order_id}/reference/... or {work_order_id}/updates/...
create table if not exists public.work_order_files (
  id uuid primary key default gen_random_uuid(),
  work_order_id uuid not null references public.work_orders (id) on delete cascade,
  update_id uuid references public.work_order_updates (id) on delete cascade,
  organization_id uuid not null references public.organizations (id) on delete cascade,
  uploaded_by uuid references public.profiles (id) on delete set null,
  kind text not null,
  name text not null,
  storage_path text not null unique,
  mime_type text,
  file_size bigint,
  created_at timestamptz not null default now(),
  constraint work_order_files_kind_check check (kind in ('reference', 'update_photo')),
  constraint work_order_files_update_link check ((kind = 'update_photo') = (update_id is not null))
);

create index if not exists work_order_files_work_order_idx on public.work_order_files (work_order_id, created_at);

-- ---------------------------------------------------------------------------
-- 2. Helpers
-- ---------------------------------------------------------------------------
create or replace function public.can_access_work_order(p_work_order_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.work_orders w
    where w.id = p_work_order_id
      and public.is_approved_user()
      and (
        (public.has_management_role() and public.same_organization(w.organization_id))
        or w.subcontractor_id = auth.uid()
      )
  );
$$;

create or replace function public.can_manage_work_order(p_work_order_id uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.work_orders w
    where w.id = p_work_order_id
      and public.has_management_role()
      and public.same_organization(w.organization_id)
  );
$$;

create or replace function public.work_order_folder_id(p_name text)
returns uuid
language sql
immutable
as $$
  select case
    when (storage.foldername(p_name))[1] ~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
      then ((storage.foldername(p_name))[1])::uuid
  end;
$$;

revoke all on function public.can_access_work_order(uuid) from public, anon;
revoke all on function public.can_manage_work_order(uuid) from public, anon;
grant execute on function public.can_access_work_order(uuid) to authenticated;
grant execute on function public.can_manage_work_order(uuid) to authenticated;
grant execute on function public.work_order_folder_id(text) to authenticated;

-- Stamps, organization and subcontractor checks; notify the subcontractor when assigned.
create or replace function public.prepare_work_order()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_project public.projects%rowtype;
begin
  select * into v_project from public.projects where id = new.project_id;
  if not found then
    raise exception 'Project not found' using errcode = '22023';
  end if;
  new.organization_id := v_project.organization_id;
  new.title := btrim(new.title);
  if not exists (
    select 1 from public.profiles p
    where p.id = new.subcontractor_id and p.role = 'subcontractor' and p.organization_id = v_project.organization_id
  ) then
    raise exception 'Choose a subcontractor from this organization' using errcode = '22023';
  end if;
  if tg_op = 'INSERT' then
    new.created_by := coalesce(new.created_by, auth.uid());
  end if;
  new.updated_by := coalesce(auth.uid(), new.updated_by);
  new.updated_at := now();
  return new;
end;
$$;

create or replace function public.notify_work_order_assigned()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_project_name text;
begin
  if tg_op = 'UPDATE' and new.subcontractor_id is not distinct from old.subcontractor_id then
    return new;
  end if;
  select name into v_project_name from public.projects where id = new.project_id;
  insert into public.notifications (organization_id, recipient_id, title, message, link, entity_type, entity_id)
  values (
    new.organization_id, new.subcontractor_id, 'New Work Order',
    'WO-' || new.work_order_number || ' · ' || new.title || ' at ' || coalesce(v_project_name, 'a Tamay project') || '.',
    '/work-orders/' || new.id, 'work_order', new.id
  );
  return new;
end;
$$;

revoke all on function public.prepare_work_order() from public, anon, authenticated;
revoke all on function public.notify_work_order_assigned() from public, anon, authenticated;

drop trigger if exists work_orders_prepare on public.work_orders;
create trigger work_orders_prepare
  before insert or update on public.work_orders
  for each row execute function public.prepare_work_order();

drop trigger if exists work_orders_notify_assigned on public.work_orders;
create trigger work_orders_notify_assigned
  after insert or update of subcontractor_id on public.work_orders
  for each row execute function public.notify_work_order_assigned();

